#!/usr/bin/env node
//
//  web-apps-packages.mjs - the Web apps section's package index, generated from data/packages.json (never hand written):
//  every published package a web page can call, grouped like the catalog, each row naming its lead call and linking to the
//  package page's one sample ("Use it"). Writes content-v2/web-apps/packages.md (the page, its .md twin and the export
//  entry); site/build.mjs and site/dsx-compile.mjs render it like every other content page.
//
import { writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { loadPackages, groupOf, GROUP_ORDER } from "../scripts/packages-lib.mjs";
import { leadActionOf } from "./packages.mjs";

const repo = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const parentOf = (p) => (/\/Modules\//.test(p.path) ? p.path.split("/Modules/").slice(-2)[0].split("/").pop() : null);
const titleOf = (p) => (parentOf(p) ? `${p.title} (${parentOf(p)})` : p.title);

export function indexRows() {
  const pkgs = loadPackages().packages
    .filter((p) => p.listed !== false && p.published && !/\/Modules\/(Backend|Http)$/.test(p.path))
    .map((p) => ({ p, a: leadActionOf(p) }))
    .filter(({ p, a }) => a && (p.actions ?? []).some((x) => x.page));
  return GROUP_ORDER.map((g) => ({
    id: g, title: g,
    rows: pkgs.filter(({ p }) => groupOf(p) === g).sort((x, y) => titleOf(x.p).localeCompare(titleOf(y.p))).map(({ p, a }) => ({
      id: p.url, title: titleOf(p), summary: p.summary, call: `await ${a.call}(${(a.params ?? []).length ? "…" : ""})`, alpha: p.maturity === "alpha",
      brand: p.icon?.brand ?? "", symbol: p.icon?.symbol ?? "shippingbox", path: `${p.url}#use-it`,
    })),
  })).filter((g) => g.rows.length);
}

export const INDEX_META = {
  title: "Package index",
  description: "Every native feature your web app can call today, with its lead call. Each links to the package's one sample and its full reference.",
};

export function indexMarkdown(groups = indexRows()) {
  const total = groups.reduce((n, g) => n + g.rows.length, 0);
  const md = [
    "---", `title: ${INDEX_META.title}`, `description: ${INDEX_META.description}`, "---", "",
    "<!-- GENERATED by site/web-apps-packages.mjs from data/packages.json: edit the generator, not this file. -->", "",
    `${total} packages your web app can call today. Add a package to your app in the console, then call it as shown. Each name links to the package's sample, its actions, results and events. Packages marked Alpha can still change.`, "",
  ];
  for (const g of groups) {
    md.push(`## ${g.title}`, "");
    for (const r of g.rows) md.push(`- [${r.title}](${r.path})${r.alpha ? " (Alpha)" : ""}: \`${r.call}\`. ${r.summary}`);
    md.push("");
  }
  md.push("The [full catalog](/packages) also lists the packages that are coming soon.", "");
  return md.join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(join(repo, "content-v2", "web-apps", "packages.md"), indexMarkdown());
  console.log("[docs.web-apps] content-v2/web-apps/packages.md");
}
