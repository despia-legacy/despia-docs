#!/usr/bin/env node
//
//  sync-dsx-facts.mjs - the DSX vocabulary the sample check validates against, extracted from the framework itself:
//    · OpenSource/Documentation/reference/StackReference.md: the universal attributes and each element's own attribute table
//    · OpenSource/Conformance/lint/facts.json: builtinTags, globalElementTags, declTags, headLanguageAttrs, toolAttrs
//  Output: data/dsx-facts.json (committed; regenerate when the framework moves).
//    DESPIA_FRAMEWORK=<framework checkout> node site/sync-dsx-facts.mjs
//
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const fw = process.env.DESPIA_FRAMEWORK;
if (!fw) { console.error("set DESPIA_FRAMEWORK to a despia-native/framework checkout"); process.exit(2); }
const repo = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ref = readFileSync(join(fw, "OpenSource/Documentation/reference/StackReference.md"), "utf8").split("\n");
const facts = JSON.parse(readFileSync(join(fw, "OpenSource/Conformance/lint/facts.json"), "utf8"));

const attrsOfRow = (row) => {
  const first = row.split("|")[1] ?? "";
  return [...first.matchAll(/`([^`]+)`/g)].map((m) => m[1].trim()).flatMap((a) => a.split(/\s*\/\s*/)).filter((a) => /^[A-Za-z:@-][\w:.-]*$/.test(a));
};

const universal = new Set();
const elements = {};
let section = null;
let tags = [];
for (const line of ref) {
  if (/^## Universal attributes/.test(line)) { section = "universal"; continue; }
  if (/^## Accessibility/.test(line)) { section = "a11y"; continue; }
  if (/^## Elements/.test(line)) { section = "elements"; continue; }
  if (/^## /.test(line) && section === "elements") { section = null; continue; }
  if (section === "elements" && /^####\s/.test(line)) {
    tags = [...line.matchAll(/`<?([A-Za-z][\w-]*)>?`/g)].map((m) => m[1]);
    for (const t of tags) elements[t] ??= [];
    continue;
  }
  // an element section may list its attributes as a sentence: "`bind` (two-way Bool), `color`, `label`, `on:change`."
  if (section === "elements" && /^`[\w:-]+`/.test(line) && tags.length) {
    const words = [...line.matchAll(/`([A-Za-z][\w:-]*)`/g)].map((m) => m[1]);
    for (const t of tags) elements[t].push(...words);
    continue;
  }
  if (!/^\|\s*`/.test(line)) continue;
  const attrs = attrsOfRow(line);
  if (section === "universal" || section === "a11y") attrs.forEach((a) => universal.add(a));
  else if (section === "elements") for (const t of tags) elements[t].push(...attrs);
}
for (const t of Object.keys(elements)) elements[t] = [...new Set(elements[t])].sort();

const out = {
  _note: "GENERATED by site/sync-dsx-facts.mjs from the framework's StackReference.md and Conformance/lint/facts.json. Do not edit.",
  universal: [...universal].sort(),
  elements,
  builtinTags: facts.builtinTags,
  globalElementTags: facts.globalElementTags,
  declTags: facts.declTags,
  headLanguageAttrs: facts.headLanguageAttrs,
  toolAttrs: facts.toolAttrs,
  entityAttrs: facts.entityAttrs,
  bareExpressionAttrs: facts.bareExpressionAttrs,
  dsxHeads: facts.dsxHeads,
};
writeFileSync(join(repo, "data", "dsx-facts.json"), JSON.stringify(out, null, 1) + "\n");
console.log(`dsx facts: ${out.universal.length} universal attributes, ${Object.keys(elements).length} elements`);
